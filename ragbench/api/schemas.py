"""Pydantic schemas for the RAGBench FastAPI backend."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


class HealthResponse(BaseModel):
    """Health check response schema."""
    status: str = Field(default="ok", description="Service health status")
    version: str = Field(default="0.1.0", description="RAGBench library version")
    service: str = Field(default="RAGBench Evaluation API", description="Service name")
    corpus_loaded: bool = Field(description="Whether the document corpus is loaded")
    corpus_doc_count: int = Field(description="Total documents indexed in the sample corpus")
    available_retrievers: List[str] = Field(
        default=["Real_BM25_Retriever"],
        description="Available real retrieval engines",
    )


class DatasetInfo(BaseModel):
    """Metadata describing an available benchmark dataset."""
    dataset_id: str = Field(description="Unique dataset identifier")
    name: str = Field(description="Human-readable dataset title")
    description: str = Field(description="Detailed overview of dataset contents")
    num_queries: int = Field(description="Number of evaluation queries in dataset")
    corpus_doc_count: int = Field(description="Number of documents in the paired corpus")
    default_k_values: List[int] = Field(description="Recommended cutoff ranks")


class DatasetListResponse(BaseModel):
    """Response containing list of available datasets."""
    datasets: List[DatasetInfo]


class EvaluationRequest(BaseModel):
    """Request payload for initiating benchmark evaluation."""
    dataset_id: str = Field(
        default="sample",
        description="Dataset identifier to evaluate against",
    )
    k_values: List[int] = Field(
        default=[1, 3, 5],
        description="Cutoff depths K for Recall@K evaluation (positive integers)",
    )
    include_baselines: bool = Field(
        default=False,
        description=(
            "Whether to include illustrative baseline rankings (predefined static rankings) "
            "alongside the live BM25 retrieval results"
        ),
    )

    @field_validator("k_values")
    @classmethod
    def validate_k_values(cls, values: List[int]) -> List[int]:
        """Ensure k_values is non-empty and contains only positive integers."""
        if not values:
            raise ValueError("k_values list cannot be empty")
        for k in values:
            if not isinstance(k, int) or isinstance(k, bool) or k <= 0:
                raise ValueError(f"All k values must be positive integers >= 1, got {k!r}")
        # Return sorted unique values
        return sorted(list(set(values)))

    @field_validator("dataset_id")
    @classmethod
    def validate_dataset_id(cls, v: str) -> str:
        """Sanitize and validate dataset identifier."""
        cleaned = v.strip().lower()
        if not cleaned:
            raise ValueError("dataset_id cannot be empty")
        return cleaned


class SystemSummary(BaseModel):
    """Summary metrics for a specific retrieval system."""
    system_name: str = Field(description="Name of the retrieval system")
    system_type: str = Field(
        description="Type of system: 'live' (dynamically computed) or 'illustrative' (static baseline)"
    )
    is_live: bool = Field(
        description="True if ranking was generated by executing an algorithm on corpus text"
    )
    description: str = Field(description="System description and execution notes")
    num_queries: int = Field(description="Total queries evaluated")
    mrr: float = Field(description="Mean Reciprocal Rank score (0.0 to 1.0)")
    mean_recall_at_k: Dict[str, float] = Field(
        description="Mean Recall at each requested K cutoff (keyed by K string)"
    )


class QueryResultDetail(BaseModel):
    """Per-query evaluation breakdown for a retrieval system."""
    query_id: str = Field(description="Benchmark query ID")
    query_text: str = Field(description="Benchmark query text")
    system_name: str = Field(description="Retrieval system evaluated")
    system_type: str = Field(description="'live' or 'illustrative'")
    total_relevant: int = Field(description="Number of ground-truth relevant documents")
    retrieved_count: int = Field(description="Number of documents returned by system")
    reciprocal_rank: float = Field(description="Reciprocal rank for this query (0.0 to 1.0)")
    recall_at_k: Dict[str, float] = Field(description="Recall@K for this query (keyed by K string)")
    retrieved_doc_ids: List[str] = Field(description="Ordered list of retrieved document IDs")


class EvaluationResponse(BaseModel):
    """Full benchmark evaluation results."""
    dataset_id: str = Field(description="Evaluated dataset ID")
    k_values: List[int] = Field(description="Evaluation cutoff depths evaluated")
    queries_evaluated: int = Field(description="Total benchmark queries evaluated")
    corpus_size: int = Field(description="Total documents in the indexed corpus")
    summaries: List[SystemSummary] = Field(
        description="Aggregated metric summaries per system"
    )
    query_results: List[QueryResultDetail] = Field(
        description="Per-query evaluation breakdown"
    )
    disclaimer: str = Field(
        description="Clear disclosure distinguishing live retrieval from illustrative baselines"
    )


class ExperimentItem(BaseModel):
    """Schema for persisted experiment run (placeholder for future persistent storage)."""
    id: str
    created_at: str
    dataset_id: str
    system_name: str
    mrr: float
